#!/usr/bin/env bash
#
# deploy-green-lms-entry.sh
#
# Prepares the green-lms portfolio entry (media assets), validates the config and
# optionally deploys it to the portfolio host and refreshes stats.
#
# Usage:
#   bash scripts/deploy-green-lms-entry.sh              # media + local validation only
#   bash scripts/deploy-green-lms-entry.sh --remote     # also rsync to the server and refresh stats
#
set -Eeuo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
LAB_DIR="${LAB_DIR:-$HOME/Nextcloud/Uni/Master/SS25/Lab}"
SRC="$LAB_DIR/lab_lms"
PROJECT_DIR="$REPO_ROOT/config/projects/green-lms"
MEDIA_DIR="$PROJECT_DIR/media"

SERVER="${SERVER:-christian-f-brinkmann.de}"
REMOTE_CONFIG="${REMOTE_CONFIG:-/container/config/personal_projects/config/projects/green-lms}"
BUILDER="${BUILDER:-portfolio-builder}"
SITE="${SITE:-https://projects.christian-f-brinkmann.de}"

REMOTE=0
for arg in "$@"; do
  case "$arg" in
    --remote) REMOTE=1 ;;
    -h|--help) sed -n '2,16p' "$0"; exit 0 ;;
    *) echo "Unknown argument: $arg" >&2; exit 2 ;;
  esac
done

log()  { printf '\n\033[1;34m==> %s\033[0m\n' "$*"; }
warn() { printf '\033[1;33mWARN:\033[0m %s\n' "$*" >&2; }
die()  { printf '\033[1;31mERROR:\033[0m %s\n' "$*" >&2; exit 1; }

[ -f "$PROJECT_DIR/project.json" ] || die "missing $PROJECT_DIR/project.json"
[ -d "$SRC" ] || die "lab_lms not found at $SRC"
command -v node >/dev/null || die "node is required for config validation and stats verification"

log "Copying media assets"
mkdir -p "$MEDIA_DIR"
copy_if_exists() { if [ -f "$1" ]; then cp "$1" "$2"; else warn "missing: $1"; fi; }
copy_if_exists "$SRC/checkpoints images/Checkpoints.png"               "$MEDIA_DIR/checkpoints.png"
copy_if_exists "$SRC/checkpoints images/Checkpoints (Autogenerated).png" "$MEDIA_DIR/checkpoints-autogenerated.png"
copy_if_exists "$SRC/checkpoints images/Checkpoints (Self-created).png"  "$MEDIA_DIR/checkpoints-self-created.png"
if [ -f "$SRC/db_diagram_green.png" ]; then
  cp "$SRC/db_diagram_green.png" "$MEDIA_DIR/database-schema.png"
elif [ -f "$LAB_DIR/db_diagram_green.png" ]; then
  cp "$LAB_DIR/db_diagram_green.png" "$MEDIA_DIR/database-schema.png"
else
  warn "missing: db_diagram_green.png (looked in lab_lms/ and the workspace root)"
fi
ls -1 "$MEDIA_DIR"

log "Validating project.json"
node -e '
  const p = require(process.argv[1]);
  const required = ["id","name","tagline","year","category","status","role","sourceType","aiUsage","aiUtilization","description","purpose","technologies","dependencies","expertise","strengths","limitations","roadmap"];
  const missing = required.filter(k => p[k] === undefined);
  if (missing.length) { console.error("missing fields:", missing.join(", ")); process.exit(1); }
  const ids = p.repos.map(r => r.name);
  console.log("id:", p.id, "| repos:", ids.join(", "));
' "$PROJECT_DIR/project.json"

log "Compiling project config"
if [ -d "$REPO_ROOT/node_modules" ]; then
  ( cd "$REPO_ROOT" && npm run compile-projects )
else
  warn "node_modules missing; run 'npm install' first if you want a local build"
fi

if [ "$REMOTE" -eq 0 ]; then
  log "Local preparation done. Re-run with --remote to deploy to $SERVER"
  exit 0
fi

log "Pre-flight on $SERVER"
ssh "$SERVER" "docker ps --format '{{.Names}}' | grep -qx '$BUILDER' || { echo 'builder container missing'; exit 1; }"
ssh "$SERVER" "docker exec $BUILDER sh -lc 'printenv GITHUB_TOKEN >/dev/null 2>&1 && echo github-token: present || echo github-token: MISSING'"
ssh "$SERVER" "docker exec $BUILDER sh -lc 'ssh -o StrictHostKeyChecking=accept-new -T git@github.com >/dev/null 2>&1; [ \$? -eq 1 ] && echo ssh-github: ok || echo ssh-github: CHECK'"

log "Uploading project entry"
rsync -a --delete "$PROJECT_DIR/" "$SERVER:$REMOTE_CONFIG/"

log "Refreshing stats (clones the 7 private mirrors via SSH)"
ssh "$SERVER" "docker exec $BUILDER npm run update-stats"

log "Rebuilding site"
ssh "$SERVER" "docker exec $BUILDER npm run build"

log "Verifying live stats"
curl -fsS "$SITE/stats.json" | node -e '
let raw = "";
process.stdin.on("data", (chunk) => { raw += chunk; });
process.stdin.on("end", () => {
  const data = JSON.parse(raw);
  const project = data.projects && data.projects["green-lms"];
  if (!project) { console.error("green-lms missing from stats.json"); process.exit(1); }
  console.log("commits:", project.stats && project.stats.commits,
              "| branches:", project.stats && project.stats.branches,
              "| loc:", project.loc && project.loc.total);
  console.log("repositories:", Object.keys(project.repoHashes || {}).join(", "));
});
'

log "Done. Open $SITE and check the green LMS card, detail page and chat."
